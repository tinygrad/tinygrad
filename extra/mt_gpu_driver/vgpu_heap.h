/*
 * gVdiVaHeapLayout40: VA heap layout for 40-bit virtual address space (for QY2 and before) on VDI
 *
 * This array defines the layout of various heaps in the 40-bit virtual address space.
 * Each entry in the array specifies the usage, base address, and size of a heap.
 *
 * The layout is as follows (in order of increasing base address):
 *
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * |         Usage           |   Base Address    |       Size        |                     Description                    |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * | HEAPUSAGE_GENERAL       | 0x40000000        | 512 GB            |                                                    |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * |                         | 0x80'40000000     | 127 GB            | Unused                                             |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * | HEAPUSAGE_FREELIST      | 0xA0'00000000     | 16 MB             | Completely reserved by KMD for PM use              |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * |                         | 0xA0'01000000     | 64 GB - 16 MB     | Unused                                             |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * | HEAPUSAGE_TEXTURESTATE  | 0xB0'00000000     | 64 GB             | KMD reservation exists at the heap end             |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * |                         | 0xC0'00000000     | 10 4GB            | Unused                                             |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * | HEAPUSAGE_PDS           | 0xDA'00000000     | 4 GB              | KMD reservation exists at the heap end             |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * |                         | 0xDB'00000000     | 20 GB             | Unused                                             |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * | HEAPUSAGE_USC           | 0xE0'00000000     | 4 GB              | KMD reservation exists at the heap end             |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * |                         | 0xE1'00000000     | 3 GB              | Unused                                             |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * | HEAPUSAGE_FW            | 0xE1'C0000000     | 1 GB              |                                                    |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * |                         | 0xE2'00000000     | 40 GB             | Unused                                             |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * | HEAPUSAGE_COMPONENTCTRL | 0xEB'00000000     | 4 GB              |                                                    |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * | HEAPUSAGE_FBCDC         | 0xEC'00000000     | 32 KB             | Has hardware access limitation of 32 KB            |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * |                         | 0xEC'00008000     | 1 GB - 32 KB      | Unused                                             |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * | HEAPUSAGE_FBCDCLARGE    | 0xEC'40000000     | 4 KB              | Has hardware access limitation of 4 KB             |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 * |                         | 0xEC'40001000     | 79 GB - 4 KB      | Unused                                             |
 * +-------------------------+-------------------+-------------------+----------------------------------------------------+
 */

#define MTGPU_VGPU_HEAP_GENERAL_BASE 0x40000000
#define MTGPU_VGPU_HEAP_GENERAL_SIZE (uint64_t)512 * 1024 * 1024 * 1024

#define MTGPU_VGPU_HEAP_PDS_BASE 0xDA00000000
#define MTGPU_VGPU_HEAP_PDS_SIZE (uint64_t)4 * 1024 * 1024 * 1024

#define MTGPU_VGPU_HEAP_USC_BASE 0xE000000000
#define MTGPU_VGPU_HEAP_USC_SIZE (uint64_t)4 * 1024 * 1024 * 1024

#define MTGPU_VGPU_HEAP_FREELIST_BASE 0xA000000000
#define MTGPU_VGPU_HEAP_FREELIST_SIZE (uint64_t)16 * 1024 * 1024

#define MTGPU_VGPU_HEAP_FW_BASE 0xE1C0000000
#define MTGPU_VGPU_HEAP_FW_SIZE (uint64_t)1024 * 1024 * 1024

#define MTGPU_VGPU_HEAP_FBCDC_BASE 0xEC00000000
#define MTGPU_VGPU_HEAP_FBCDC_SIZE (uint64_t)8 * 1024 * 1024

#define MTGPU_VGPU_HEAP_FBCDCLARGE_BASE 0xEC40000000
#define MTGPU_VGPU_HEAP_FBCDCLARGE_SIZE (uint64_t)128 * 1024

#define MTGPU_VGPU_HEAP_COMPONENTCTRL_BASE 0xEB00000000
#define MTGPU_VGPU_HEAP_COMPONENTCTRL_SIZE (uint64_t)4 * 1024 * 1024 * 1024

#define MTGPU_VGPU_HEAP_TEXTURESTATE_BASE 0xB000000000
#define MTGPU_VGPU_HEAP_TEXTURESTATE_SIZE (uint64_t)64 * 1024 * 1024 * 1024

